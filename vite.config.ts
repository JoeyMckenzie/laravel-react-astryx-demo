import inertia from '@inertiajs/vite';
import { wayfinder } from '@laravel/vite-plugin-wayfinder';
import babel from '@rolldown/plugin-babel';
import stylex from '@stylexjs/unplugin';
import react, { reactCompilerPreset } from '@vitejs/plugin-react';
import laravel from 'laravel-vite-plugin';
import type { Plugin } from 'vite';
import { defineConfig, lazyPlugins } from 'vite-plus';

// In an Amp orb (.amp/services.yaml), Vite sits behind a portal URL and proxies
// every request it does not serve itself to `php artisan serve`.
const portalUrl = process.env.AMP_ORB
    ? process.env.PUBLIC_URL?.replace(/\/$/, '')
    : undefined;
const laravelDevUrl = process.env.LARAVEL_DEV_URL;

// StyleX's own generateBundle re-hashes the CSS file it appends to, which drops
// resources/css/app.css from Laravel's manifest under Vite+ (Rolldown). Keep its
// transform and append the collected CSS to that asset in place instead.
function stylexPlugins(): Plugin[] {
    const { generateBundle: _, ...transform } = stylex.vite({
        useCSSLayers: true,
    }) as Plugin & { __stylexCollectCss?: () => string };
    const collectCss = (transform as { __stylexCollectCss?: () => string })
        .__stylexCollectCss;

    return [
        transform,
        {
            name: 'stylex:append-to-app-css',
            enforce: 'post',
            generateBundle(_options, bundle) {
                const css = collectCss?.();
                const appCss = Object.values(bundle).find(
                    (file) =>
                        file.type === 'asset' &&
                        file.originalFileNames.includes(
                            'resources/css/app.css',
                        ),
                );

                if (css && appCss?.type === 'asset') {
                    appCss.source = `${appCss.source.toString()}\n${css}`;
                }
            },
        },
    ];
}

export default defineConfig({
    plugins: lazyPlugins(() => [
        laravel({
            input: ['resources/css/app.css', 'resources/js/app.tsx'],
            refresh: true,
        }),
        inertia(),
        // Compiles our own stylex.create() calls; Astryx ships prebuilt CSS (astryx.css).
        ...stylexPlugins(),
        react(),
        babel({
            presets: [reactCompilerPreset()],
        }),
        wayfinder({
            formVariants: true,
        }),
    ]),
    server: {
        ...(portalUrl &&
            laravelDevUrl && {
                origin: portalUrl,
                hmr: { protocol: 'wss', clientPort: 443 },
                proxy: {
                    '^/(?!@vite/|@id/|@fs/|@react-refresh|resources/|node_modules/|virtual:stylex|astryx-themes.ts)':
                        { target: laravelDevUrl },
                },
            }),
        watch: {
            ignored: [
                '**/.agents/**',
                '**/.claude/**',
                '**/.cursor/**',
                '**/.junie/**',
                '**/vendor/**',
            ],
        },
    },
    lint: {
        ignorePatterns: [
            'vendor/**',
            'node_modules/**',
            'public/**',
            'bootstrap/ssr/**',
            'astryx-themes.ts',
            'resources/js/actions/**',
            'resources/js/routes/**',
            'resources/js/wayfinder/**',
        ],
        options: {
            denyWarnings: true,
            typeAware: true,
        },
    },
    fmt: {
        printWidth: 80,
        tabWidth: 4,
        singleQuote: true,
        semi: true,
        singleAttributePerLine: false,
        htmlWhitespaceSensitivity: 'css',
        ignorePatterns: [
            '.github/**',
            'composer.json',
            // Generated by the Astryx CLI (`astryx init`, `astryx theme add`).
            'AGENTS.md',
            'astryx-themes.ts',
            'resources/views/mail/*',
        ],
    },
});
